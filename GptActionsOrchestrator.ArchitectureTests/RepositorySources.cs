using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

using NUnit.Framework;

namespace GptActionsOrchestrator.ArchitectureTests
{
    internal static class RepositorySources
    {
        public static readonly string[] ProjectNames =
        [
            "GptActionsOrchestrator",
            "GptActionsOrchestrator.ArchitectureTests",
            "GptActionsOrchestrator.IntegrationTests",
            "GptActionsOrchestrator.UnitTests"
        ];

        public static readonly string Root = FindRoot();

        public static IEnumerable<string> Files(string projectName)
        {
            string directory = Path.Combine(Root, projectName);
            Assert.That(Directory.Exists(directory), Is.True, $"Missing source project: {directory}");
            string[] files = Directory.GetFiles(directory, "*.cs", SearchOption.AllDirectories)
                .Where(IsHandwritten)
                .Order(StringComparer.Ordinal)
                .ToArray();
            Assert.That(files, Is.Not.Empty, $"No handwritten C# sources in {directory}");

            return files;
        }

        public static SyntaxNode Parse(string path) =>
            CSharpSyntaxTree.ParseText(
                File.ReadAllText(path),
                new CSharpParseOptions(LanguageVersion.Preview),
                path).GetRoot();

        private static string FindRoot()
        {
            DirectoryInfo? directory = new(TestContext.CurrentContext.TestDirectory);

            while (directory is not null)
            {
                if (File.Exists(Path.Combine(directory.FullName, "GptActionsOrchestrator.slnx")))
                {
                    return directory.FullName;
                }

                directory = directory.Parent;
            }

            throw new DirectoryNotFoundException(
                "Architecture tests require the repository checkout, including its solution and sources.");
        }

        private static bool IsHandwritten(string path)
        {
            string relativePath = Path.GetRelativePath(Root, path);
            string[] segments = relativePath.Split(Path.DirectorySeparatorChar);

            return !segments.Any(segment => segment is "bin" or "obj") &&
                !path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase) &&
                !path.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase) &&
                !path.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase) &&
                !File.ReadLines(path).Take(2).Any(line =>
                    line.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase));
        }
    }
}
